export const SUBJECT_CODES = SUBJECTS.map((s) => s.code) as [string, ...string[]];

export const isSubjectCode = (code: string) => BY_CODE.has(code);

/** 显示用：“计算机科学 (198)”；不认识的旧课程名原样返回 */
export function subjectLabel(code: string, locale: Locale) {
  const s = BY_CODE.get(code);
  return s ? `${s[locale]} (${code})` : code;
}

/** 给 Gemini 的提示词里用英文官方名，更准确 */
export const subjectForPrompt = (code: string) => {
  const s = BY_CODE.get(code);
  return s ? `${s.en} (${code})` : code;
};
